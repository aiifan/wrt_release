#!/usr/bin/env bash
# ============================================================
# 保留自定义配置 + 同步上游更新（手动逐行执行版）
#
# ⚠️ 请勿直接运行本文件！按下方步骤逐行复制到终端执行。
# ⚠️ 每执行到关键节点，先确认输出结果再继续下一步。
#
# 对应上游 issue：
#   https://github.com/ZqinKing/wrt_release/issues/132
#
# 核心思路：
#   1. 把你的自定义改动打包成 patch
#   2. 把本地仓库重置为上游最新
#   3. 把你的 patch 重新应用回去
#   4. 提交推送
# ============================================================

# ------------------------------------------------------------
# [第 0 步] 首次准备（只执行一次，已配置过可跳过）
#   添加上游仓库为 remote（地址是原作者仓库，注意不是示例里
#   写错的地址）
# ------------------------------------------------------------
git remote add upstream https://github.com/ZqinKing/wrt_release.git

# 只跟踪上游 main 分支，不拉取其他分支
git config remote.upstream.fetch "+refs/heads/main:refs/remotes/upstream/main"

# 确认 remote 配置结果
git remote -v


# ------------------------------------------------------------
# [第 1 步] 同步前检查：本地工作区必须干净
# ------------------------------------------------------------
git status
# 若显示未提交的改动，先手动处理：
#   git add -A && git commit -m "自定义改动"     # 提交改动
# 确认干净（Nothing to commit）后再继续，否则你的改动
# 会丢失（reset --hard 会清掉未提交内容）


# ------------------------------------------------------------
# [第 2 步] 拉取上游最新代码
# ------------------------------------------------------------
git checkout main
git fetch --no-tags upstream


# ------------------------------------------------------------
# [第 3 步] 生成你的自定义改动补丁
#    对比"上游最新"和"你的 main"，差异导出为 patch 文件
#    patch 会生成在仓库上一级目录（仓库外，避免被 reset 影响）
# ------------------------------------------------------------
git diff upstream/main...main > ../自定义插件.patch

# 确认 patch 非空（有内容才说明你的改动被保留了）
wc -l ../自定义插件.patch


# ------------------------------------------------------------
# [第 4 步] 重置本地仓库到上游最新版本
#    ⚠️ 破坏性操作：本地所有与上游的差异都会被清空，
#        只保留已打出的 patch 文件（在上一步已生成）
# ------------------------------------------------------------
git reset --hard upstream/main


# ------------------------------------------------------------
# [第 5 步] 把你的自定义补丁应用回去
#    --3way 启用三方合并，冲突时会标记出来
# ------------------------------------------------------------
git apply --3way ../自定义插件.patch

# 若提示冲突（conflict），需要手动解决：
#   git status                # 查看冲突文件
#   手动编辑冲突文件          # 解决 >>> === <<< 标记
#   git add <冲突文件>        # 标记已解决


# ------------------------------------------------------------
# [第 6 步] 验证、提交并推送
# ------------------------------------------------------------
# 确认改动符合预期
git status

# 提交你的自定义改动
git commit -a -m "自定义插件"

# 强制推送（因本地历史已重置，普通 push 会被拒绝）
git push -f origin main